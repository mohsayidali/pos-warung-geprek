-- Settings: bisa dibaca anon/authenticated (agar logo tampil di halaman Login),
-- namun hanya user login (authenticated) yang boleh mengubah/menyimpan.
DROP POLICY IF EXISTS "settings_select_public" ON public.settings;
CREATE POLICY "settings_select_public"
  ON public.settings FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "settings_write_authenticated" ON public.settings;
CREATE POLICY "settings_write_authenticated"
  ON public.settings FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);

